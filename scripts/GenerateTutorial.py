"""Compile owner-authored dialogue fields to inert UTF-8 JSON; never execute script text."""
import sys
import json
import re
from pathlib import Path


def incoming_variant(line):
    """Select a complete line from an N or PB choice in the unified script."""
    match = re.match(r'\s*Variant \w+ — from ((?:N|PB)[\w-]+) / (.+) \[([^]]+)\]', line)
    if not match:
        match = re.match(r'IF ((?:N|PB)[\w-]+) CHOICE "([^"]+)" \[([^]]+)\]', line)
    return {'from': match[1], 'label': match[2], 'expression': match[3]} if match else None


root = Path(__file__).resolve().parent.parent
source_path = 'personalities/tutorial/tutorial.txt'
source = (root / source_path).read_text(encoding='utf-8-sig')
headers = list(re.finditer(
    r'^((?:N\d{3}(?:[AB]|-[AB])?|[BC]\d{3}|PB(?:\d{3}|-R\d{2}))) '
    r'(?:\[([^\]]+)\]|—[^\n]+)$', source, re.M))
sections = list(re.finditer(r'^={6,}\n([^\n]+)\n={6,}$', source, re.M))
beats = {}
phases = {}
for i, h in enumerate(headers):
    if h[1] in beats:
        raise SystemExit(f'Duplicate tutorial beat: {h[1]}')
    body = source[h.end():headers[i + 1].start() if i + 1 < len(headers) else len(source)]
    entry = {'expression': h[2] or 'idle', 'variants': [], 'choices': []}
    variant = None
    for line in body.splitlines():
        incoming = incoming_variant(line)
        if incoming is not None:
            variant = incoming
        if re.match(r'\s*NORM:', line):
            text = line.split('NORM:', 1)[1].strip()
            if variant is not None:
                variant['text'] = text
                entry['variants'].append(variant)
                variant = None
            elif 'text' not in entry:
                entry['text'] = text
        if line.startswith('UI:'):
            quoted = re.findall(r'"([^"]+)"', line)
            if len(quoted) >= 2:
                entry['choices'] = quoted[:2]
    assert 'text' in entry or entry['variants'], h[1]
    beats[h[1]] = entry
    if h[1].startswith('PB'):
        section = 'Plug Board reactions' if '-R' in h[1] else ('Plug Board introduction' if h[1] < 'PB009' else 'Plug Board assignment')
    else:
        section = next((section[1] for section in reversed(sections) if section.start() < h.start()), None)
    if section is None:
        raise SystemExit(f'Tutorial beat {h[1]} has no named phase.')
    phases.setdefault(section, {})[h[1]] = entry
# Validate references as well as generated bytes: a typo must fail the build,
# rather than silently selecting a different incoming dialogue variant.
for beat_id, entry in beats.items():
    for variant in entry['variants']:
        if variant['from'] not in beats or variant['label'] not in beats[variant['from']]['choices']:
            raise SystemExit(f"Invalid incoming choice for {beat_id}: {variant['from']} / {variant['label']}")
out = json.dumps(beats, ensure_ascii=False, indent=2)
# Keep lesson phases, working greetings, recovery lines and click reactions independent.
# MSVC C2026 limits each literal to 16,380 characters. A conservative UTF-8
# byte budget also guards multibyte dialogue; never concatenate literals at
# compile time. A phase that outgrows the budget fails with its name.
literal_byte_limit = 8192
fragments = []
for title, records in phases.items():
    # Strip only the outer object braces/newlines, keeping complete beat records.
    fragment = json.dumps(records, ensure_ascii=False, indent=2)[2:-2]
    if len(fragment.encode('utf-8')) > literal_byte_limit:
        raise SystemExit(f'Tutorial phase "{title}" exceeds the {literal_byte_limit}-byte literal budget; split the phase.')
    if ')AHTUTORIAL"' in fragment:
        raise SystemExit(f'Tutorial phase "{title}" conflicts with the C++ raw-string delimiter.')
    fragments.append('    // ' + title + '\n    R"AHTUTORIAL(' + fragment + ')AHTUTORIAL"')
literal_array = ',\n'.join(fragments)
compiled = (f'// Generated by scripts/GenerateTutorial.py from {source_path}.\n'
    '#include "model/tutorial.h"\n#include <string>\nnamespace audiohole {\n'
    'std::string_view tutorial_catalog() {\n'
    '    // Separate named phases stay below MSVC literal limits.\n'
    '    static constexpr std::string_view phases[] = {\n' + literal_array + '\n    };\n'
    '    // Join once on first control-thread use. The returned view has process lifetime.\n'
    '    static const std::string data = [] {\n'
    '        std::string result;\n'
    f'        result.reserve({len(out.encode("utf-8"))});\n'
    '        result = "{\\n";\n'
    '        bool first = true;\n'
    '        for (const auto phase : phases) {\n'
    '            if (!first)\n'
    '                result += ",\\n";\n'
    '            result.append(phase);\n'
    '            first = false;\n'
    '        }\n'
    '        result += "\\n}";\n'
    '        return result;\n'
    '    }();\n'
    '    return data;\n}\n}\n')
path = root / 'src/model/tutorial_catalog.cpp'
if '--check' in sys.argv:
    actual = path.read_text(encoding='utf-8')
    if actual != compiled:
        raise SystemExit('Tutorial catalogue differs from the owner script; regenerate it.')
    literals = re.findall(r'R"AHTUTORIAL\((.*?)\)AHTUTORIAL"', actual, re.S)
    if not literals or any(len(value.encode('utf-8')) > literal_byte_limit for value in literals):
        raise SystemExit('Tutorial catalogue exceeds the MSVC-safe literal byte budget.')
    if '{\n' + ',\n'.join(literals) + '\n}' != out:
        raise SystemExit('Tutorial catalogue phases do not preserve the complete UTF-8 JSON.')
    print(f'PASS: compiled tutorial matches the owner script; {len(literals)} named, MSVC-safe phases')
else:
    path.write_text(compiled, encoding='utf-8')
    print(f'{len(beats)} authored dialogue beats compiled')
