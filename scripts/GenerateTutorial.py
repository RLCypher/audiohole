"""Compile owner-authored dialogue fields to inert UTF-8 JSON; never execute script text."""
import sys
import json
import re
from pathlib import Path
root = Path(__file__).resolve().parent.parent
source = (root / 'docs/tutorial/Norm-script.txt').read_text(encoding='utf-8-sig')
headers = list(re.finditer(r'^(N\d{3}(?:[AB]|-[AB])?|[BC]\d{3}) \[([^\]]+)\]$', source, re.M))
beats = {}
for i, h in enumerate(headers):
    body = source[h.end():headers[i + 1].start() if i + 1 < len(headers) else len(source)]
    entry = {'expression': h[2], 'variants': [], 'choices': []}
    variant = None
    for line in body.splitlines():
        incoming = re.match(r'  Variant \w+ — from (N[\w-]+) / (.+) \[([^]]+)\]', line)
        if incoming:
            variant = {'from': incoming[1], 'label': incoming[2], 'expression': incoming[3]}
        if re.match(r'\s*NORM:', line):
            text = line.split('NORM:', 1)[1].strip()
            if variant is not None:
                variant['text'] = text
                entry['variants'].append(variant)
                variant = None
            elif 'text' not in entry:
                entry['text'] = text
        if line.startswith('UI:'):
            quoted = re.findall(r'"([^"]+)"', line)
            if len(quoted) >= 2:
                entry['choices'] = quoted[:2]
    assert 'text' in entry or entry['variants'], h[1]
    beats[h[1]] = entry
# Validate references as well as generated bytes: a typo must fail the build,
# rather than silently selecting a different incoming dialogue variant.
for beat_id, entry in beats.items():
    for variant in entry['variants']:
        if variant['from'] not in beats or variant['label'] not in beats[variant['from']]['choices']:
            raise SystemExit(f"Invalid incoming choice for {beat_id}: {variant['from']} / {variant['label']}")
out = json.dumps(beats, ensure_ascii=False, indent=2)
compiled = ('// Generated by scripts/GenerateTutorial.py from docs/tutorial/Norm-script.txt.\n'
    '#include "model/tutorial.h"\nnamespace audiohole {\n'
    'std::string_view tutorial_catalog() { return R"AHTUTORIAL(' + out + ')AHTUTORIAL"; }\n}\n')
path = root / 'src/model/tutorial_catalog.cpp'
if '--check' in sys.argv:
    if path.read_text(encoding='utf-8') != compiled:
        raise SystemExit('Tutorial catalogue differs from the owner script; regenerate it.')
    print('PASS: compiled tutorial matches the owner script')
else:
    path.write_text(compiled, encoding='utf-8')
    print(f'{len(beats)} authored dialogue beats compiled')
